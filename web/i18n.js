function traditionalize(source) {
  let out = source;
  for (const [from, to] of PHRASES) out = out.split(from).join(to);
  return out;
}

const dictionaries = {
  en: new Map(Object.entries(MESSAGES.en)),
  es: new Map(Object.entries(MESSAGES.es)),
  'zh-TW': new Map(),
};
for (const key of Object.keys(MESSAGES.en)) dictionaries['zh-TW'].set(key, traditionalize(key));

let current = 'zh-CN';
const originals = new WeakMap();
const attrOriginals = new WeakMap();

function lookup(text) {
  if (current === 'zh-CN') return null;
  return dictionaries[current]?.get(text) || null;
}

export function t(text, vars = {}) {
  const translated = lookup(String(text)) || String(text);
  return translated.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`);
}

function shouldSkip(node) {
  const el = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
  return el?.closest?.('[data-i18n-skip]') || el?.closest?.('script,style,code');
}

export function translateDom(root = document) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (shouldSkip(node)) continue;
    const original = originals.get(node) ?? node.nodeValue;
    originals.set(node, original);
    const key = original.trim();
    if (!key) continue;
    const target = lookup(key);
    if (target) node.nodeValue = original.replace(key, target);
    else if (current === 'zh-CN') node.nodeValue = original;
  }
  for (const el of root.querySelectorAll?.('[placeholder],[title],[aria-label]') || []) {
    if (shouldSkip(el)) continue;
    let map = attrOriginals.get(el);
    if (!map) { map = {}; attrOriginals.set(el, map); }
    for (const attr of ['placeholder', 'title', 'aria-label']) {
      if (!el.hasAttribute(attr)) continue;
      if (!(attr in map)) map[attr] = el.getAttribute(attr);
      const key = String(map[attr]).trim();
      const target = lookup(key);
      if (target) el.setAttribute(attr, String(map[attr]).replace(key, target));
      else if (current === 'zh-CN') el.setAttribute(attr, map[attr]);
    }
  }
  if (root === document) {
    const originalTitle = 'XI Node · 本地 AI 主机';
    const target = lookup(originalTitle);
    if (target) document.title = target;
    else if (current === 'zh-CN') document.title = originalTitle;
  }
}

export function getLanguage() { return current; }

export function setLanguage(lang) {
  if (!LANGUAGES.some((x) => x.id === lang)) return;
  current = lang;
  document.documentElement.lang = lang;
  localStorage.setItem('xi.lang', lang);
  document.querySelectorAll('#langSelect').forEach((el) => { el.value = lang; });
  translateDom(document);
  window.dispatchEvent(new CustomEvent('xi:lang', { detail: { lang } }));
}

export function initI18n() {
  const saved = localStorage.getItem('xi.lang');
  current = LANGUAGES.some((x) => x.id === saved) ? saved : 'zh-CN';
  document.documentElement.lang = current;
  translateDom(document);
  const select = document.querySelector('#langSelect');
  if (select) { select.value = current; select.addEventListener('change', () => setLanguage(select.value)); }
  return current;
}